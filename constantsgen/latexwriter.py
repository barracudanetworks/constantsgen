import re

# A name within a value, which may be a reference to another constant.
names_in_value = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")


def command_name(name):
    """Latex does not support underscores in commands."""
    return name.replace("_", "")


def command_body(value, commands):
    """Rewrite a value so that it is usable as a command body.

    Values are raw text which may name other constants, so a name that is
    generated as a command becomes a reference to that command; the reference
    would otherwise be lost. Every underscore left after that is escaped,
    since Latex reads a bare one as a subscript.
    """
    def replacement(match):
        name = match.group()
        if name in commands:
            return f"\\{commands[name]}"

        return name.replace("_", r"\_")

    return names_in_value.sub(replacement, str(value))


class LatexWriter:
    def __init__(self, constants):
        self.constants = constants

    def write(self, out):
        out.write("% This file was generated by generate_constants.\n\n")

        # Every name this writes, so that values referring to them can be
        # rewritten to refer to the commands instead.
        commands = {}
        for enum in self.constants.enum_values.values():
            for name in enum:
                commands[name] = command_name(name)

        for name in self.constants.constant_values:
            commands[name] = command_name(name)

        for enum in self.constants.enum_values.values():
            out.write("\n")
            for name, value in enum.items():
                out.write(f"\\newcommand{{\\{command_name(name)}}}"
                          f"{{{command_body(value, commands)}}}\n")

        for name, value in self.constants.constant_values.items():
            out.write(f"\\newcommand{{\\{command_name(name)}}}"
                      f"{{{command_body(value, commands)}}}\n")
